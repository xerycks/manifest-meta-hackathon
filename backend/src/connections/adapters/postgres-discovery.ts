import type { ClientBase } from "pg"

import {
  DISCOVERY_LIMITS,
  DiscoveryLimitExceeded,
  type DiscoveredColumn,
  type DiscoveredMetadata,
  type DiscoveredObject,
  type DiscoveryRequest,
  type ManifestObjectKind,
} from "./types.js"

/** Objects whose columns are read per query, which is also the progress granularity. */
const COLUMN_BATCH_SIZE = 200
const MAX_COMMENT_CHARS = 4_000
const MAX_DEFAULT_CHARS = 1_000
/** Longer view definitions are left out rather than cut mid-statement. */
const MAX_VIEW_DEFINITION_CHARS = 20_000
const MAX_ENUM_VALUES = 200

const KINDS: Record<string, ManifestObjectKind> = {
  r: "table",
  v: "view",
  m: "materialized_view",
  p: "partitioned_table",
  f: "foreign_table",
}

// Partitions are skipped: they are queried through their partitioned parent.
// reltuples is the planner's estimate (-1 until the table is first analyzed).
const OBJECTS_SQL = `
  SELECT c.oid, n.nspname AS schema_name, c.relname AS object_name, c.relkind,
         left(obj_description(c.oid, 'pg_class'), ${MAX_COMMENT_CHARS}) AS comment,
         CASE WHEN c.relkind IN ('r', 'm') AND c.reltuples >= 0 THEN c.reltuples::bigint END AS estimated_rows,
         CASE WHEN c.relkind IN ('v', 'm') THEN
           (SELECT CASE WHEN length(def) <= ${MAX_VIEW_DEFINITION_CHARS} THEN def END
              FROM pg_catalog.pg_get_viewdef(c.oid, true) AS def)
         END AS view_definition
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = ANY ($1::text[])
     AND c.relkind IN ('r', 'v', 'm', 'p', 'f')
     AND NOT c.relispartition
     AND has_schema_privilege(n.oid, 'USAGE')
     AND has_table_privilege(c.oid, 'SELECT')
   ORDER BY n.nspname, c.relname
   LIMIT $2`

const COUNT_COLUMNS_SQL = `
  SELECT count(*)::int AS count
    FROM pg_catalog.pg_attribute
   WHERE attrelid = ANY ($1::oid[]) AND attnum > 0 AND NOT attisdropped`

const COLUMNS_SQL = `
  SELECT a.attrelid AS oid, a.attname::text AS name, a.attnum AS ordinal,
         format_type(a.atttypid, a.atttypmod) AS data_type,
         NOT a.attnotnull AS nullable,
         left(CASE
           WHEN a.attidentity = 'a' THEN 'generated always as identity'
           WHEN a.attidentity = 'd' THEN 'generated by default as identity'
           WHEN a.attgenerated = 's' THEN 'generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
           ELSE pg_get_expr(d.adbin, d.adrelid)
         END, ${MAX_DEFAULT_CHARS}) AS default_value,
         EXISTS (
           SELECT 1 FROM pg_catalog.pg_constraint pk
            WHERE pk.conrelid = a.attrelid AND pk.contype = 'p' AND a.attnum = ANY (pk.conkey)
         ) AS is_primary_key,
         (SELECT array_agg(e.label ORDER BY e.position)
            FROM (SELECT enumlabel::text AS label, enumsortorder AS position
                    FROM pg_catalog.pg_enum
                   WHERE enumtypid = a.atttypid
                   ORDER BY enumsortorder
                   LIMIT ${MAX_ENUM_VALUES}) AS e
         ) AS enum_values,
         left(col_description(a.attrelid, a.attnum), ${MAX_COMMENT_CHARS}) AS comment
    FROM pg_catalog.pg_attribute a
    LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
   WHERE a.attrelid = ANY ($1::oid[]) AND a.attnum > 0 AND NOT a.attisdropped
   ORDER BY a.attrelid, a.attnum`

// Only foreign keys between discovered objects; conparentid = 0 skips the
// per-partition copies PostgreSQL keeps for partitioned tables.
const RELATIONSHIPS_SQL = `
  SELECT con.conname AS constraint_name, con.conrelid AS from_oid, con.confrelid AS to_oid,
         ARRAY(SELECT a.attname::text
                 FROM unnest(con.conkey) WITH ORDINALITY AS k(attnum, position)
                 JOIN pg_catalog.pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.attnum
                ORDER BY k.position) AS from_columns,
         ARRAY(SELECT a.attname::text
                 FROM unnest(con.confkey) WITH ORDINALITY AS k(attnum, position)
                 JOIN pg_catalog.pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.attnum
                ORDER BY k.position) AS to_columns
    FROM pg_catalog.pg_constraint con
   WHERE con.contype = 'f'
     AND con.conparentid = 0
     AND con.conrelid = ANY ($1::oid[])
     AND con.confrelid = ANY ($1::oid[])
   ORDER BY con.conrelid, con.conname
   LIMIT $2`

interface ObjectRow {
  oid: number
  schema_name: string
  object_name: string
  relkind: string
  comment: string | null
  estimated_rows: string | null
  view_definition: string | null
}

interface ColumnRow {
  oid: number
  name: string
  ordinal: number
  data_type: string
  nullable: boolean
  default_value: string | null
  is_primary_key: boolean
  enum_values: string[] | null
  comment: string | null
}

interface RelationshipRow {
  constraint_name: string
  from_oid: number
  to_oid: number
  from_columns: string[]
  to_columns: string[]
}

const count = (value: number) => value.toLocaleString("en-US")

/**
 * Reads tables, views, columns, and foreign keys of the requested schemas from
 * pg_catalog. The caller runs it inside one read-only snapshot transaction.
 */
export async function readPostgresMetadata(
  client: ClientBase,
  request: DiscoveryRequest,
): Promise<DiscoveredMetadata> {
  const { schemas, signal, onProgress } = request

  await onProgress({ phase: "reading_objects", objectsDone: 0, objectsTotal: null })
  const objectRows = (
    await client.query<ObjectRow>(OBJECTS_SQL, [schemas, DISCOVERY_LIMITS.objects + 1])
  ).rows
  if (objectRows.length > DISCOVERY_LIMITS.objects) {
    throw new DiscoveryLimitExceeded(
      `The selected schemas have more than ${count(DISCOVERY_LIMITS.objects)} tables and views, the most one refresh reads. Select fewer schemas.`,
    )
  }
  signal.throwIfAborted()

  const oids = objectRows.map((row) => row.oid)
  const total = oids.length
  await onProgress({ phase: "reading_columns", objectsDone: 0, objectsTotal: total })
  const columnCount = (await client.query<{ count: number }>(COUNT_COLUMNS_SQL, [oids])).rows[0]
  if ((columnCount?.count ?? 0) > DISCOVERY_LIMITS.columns) {
    throw new DiscoveryLimitExceeded(
      `The selected schemas have more than ${count(DISCOVERY_LIMITS.columns)} columns, the most one refresh reads. Select fewer schemas.`,
    )
  }

  const columnsByOid = new Map<number, DiscoveredColumn[]>(oids.map((oid) => [oid, []]))
  for (let start = 0; start < total; start += COLUMN_BATCH_SIZE) {
    signal.throwIfAborted()
    const { rows } = await client.query<ColumnRow>(COLUMNS_SQL, [
      oids.slice(start, start + COLUMN_BATCH_SIZE),
    ])
    for (const row of rows) {
      columnsByOid.get(row.oid)?.push({
        name: row.name,
        ordinal: row.ordinal,
        dataType: row.data_type,
        nullable: row.nullable,
        defaultValue: row.default_value,
        isPrimaryKey: row.is_primary_key,
        enumValues: row.enum_values,
        comment: row.comment,
        details: null,
      })
    }
    await onProgress({
      phase: "reading_columns",
      objectsDone: Math.min(start + COLUMN_BATCH_SIZE, total),
      objectsTotal: total,
    })
  }
  signal.throwIfAborted()

  await onProgress({ phase: "reading_relationships", objectsDone: total, objectsTotal: total })
  const relationshipRows = (
    await client.query<RelationshipRow>(RELATIONSHIPS_SQL, [
      oids,
      DISCOVERY_LIMITS.relationships + 1,
    ])
  ).rows
  if (relationshipRows.length > DISCOVERY_LIMITS.relationships) {
    throw new DiscoveryLimitExceeded(
      `The selected schemas have more than ${count(DISCOVERY_LIMITS.relationships)} foreign keys, the most one refresh reads. Select fewer schemas.`,
    )
  }
  signal.throwIfAborted()

  const byOid = new Map(objectRows.map((row) => [row.oid, row]))
  const objects: DiscoveredObject[] = objectRows.map((row) => ({
    schema: row.schema_name,
    name: row.object_name,
    kind: KINDS[row.relkind] ?? "table",
    comment: row.comment,
    estimatedRows: row.estimated_rows === null ? null : Number(row.estimated_rows),
    viewDefinition: row.view_definition,
    columns: columnsByOid.get(row.oid) ?? [],
    keepColumns: false,
    details: null,
  }))
  const relationships = relationshipRows.flatMap((row) => {
    const from = byOid.get(row.from_oid)
    const to = byOid.get(row.to_oid)
    if (!from || !to) return []
    return [
      {
        constraintName: row.constraint_name,
        from: { schema: from.schema_name, name: from.object_name, columns: row.from_columns },
        to: { schema: to.schema_name, name: to.object_name, columns: row.to_columns },
      },
    ]
  })
  return { objects, relationships }
}
